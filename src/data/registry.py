"""Dataset registry: lanes, license snapshots, and a permanent blocklist.

Why this is code and not a policy document
------------------------------------------
A policy restrains nobody at 2 AM before a deadline. The registry does, because
every fetch, training run and calibration build goes through it, and it raises
rather than warns. The three failure modes it exists to prevent are all ones
that have actually happened to other companies:

- **Shipping a model fine-tuned on research-only data.** The license violation
  is permanent and the weights are the evidence. Lane R data therefore loads
  only through the eval harness; the training and calibration paths refuse it.
- **Building on retracted data.** DukeMTMC was withdrawn after an ethics
  scandal; MS-Celeb was withdrawn. Both, and their derivatives, are permanent
  ``blocked=True`` entries the registry knows by name, so a future fetch fails
  loudly with the retraction reason rather than quietly succeeding from a
  mirror.
- **Trusting a license class from memory.** Licenses change and recollections
  are wrong. Every entry ships with a ``hypothesis_class`` — explicitly a
  starting hypothesis — and nothing can be fetched until a human records a
  :class:`LicenseSnapshot` with a URL, a date and a hash of the text they
  actually read. When the upstream text changes later, the hash mismatch
  surfaces it.

The lanes
---------
- ``S`` — Synthetic, generated by us, every asset in the stack
  commercially cleared. Allowed: everything (train, calibrate, eval).
- ``R`` — Research-licensed public datasets. Allowed: eval and model
  selection ONLY.
- ``C`` — Consented, self-collected (Site Zero, design partners under
  data-use contracts). Allowed: everything, and the only lane admissible
  for INT8 calibration.
- ``C_pending_consent`` — Self-collected footage with NO consent record
  attached for the purpose at hand. Allowed: NOTHING — rejected by every
  training, calibration, and eval loader until a ``ConsentRecord`` is
  attached (Day 23).

Lane S is not automatically clean: several synthetic-human datasets are built
on SMPL body models whose commercial use needs a separate Meshcapade license.
Synthetic means "no consent debt", not "no license". The snapshot requirement
applies to lane S like everything else.

``C_pending_consent`` (Day 23) exists for a specific, real gap: an archive
recorded for one purpose (e.g. premises security) does not automatically
carry consent for a DIFFERENT purpose (AI development) — the DPDP Act,
2023 treats purpose as part of what consent covers, so a purpose change
generally needs its own notice and consent. Registering such an archive
as lane ``C`` outright would misrepresent it as already-consented; leaving
it out of the registry entirely would make it invisible rather than
correctly gated. ``C_pending_consent`` is the third state this project's
binary consent model (:mod:`scripts.ingest_capture`: refuse outright, or
proceed) did not have a name for: *known to exist, not yet usable, and
constructable/listable so the gap itself is a recorded, visible fact
rather than a silent absence.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path
from types import FrameType
from typing import Any, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field

Lane = Literal["S", "R", "C", "C_pending_consent"]

ConsentPosture = Literal["staged_actors", "public_cctv_no_consent", "unknown"]
"""Whether the PEOPLE ON CAMERA in a lane-R dataset were performers under a
research programme, or unconsenting subjects of real, uncontrolled
surveillance footage (Day 35) — a distinction this project had left
implicit for thirty days despite it mattering as much as ``hypothesis_class``
does for license. Deliberately separate from two adjacent concepts it is
easy to conflate with:

- ``hypothesis_class`` / :class:`LicenseSnapshot` govern the LICENSE on the
  recording — who may copy, redistribute, or train on it. A dataset can be
  perfectly clear on license (public research release) while its subjects
  never consented to being filmed at all (``public_cctv_no_consent``); the
  two questions are independent and a clean license snapshot answers
  neither.
- :class:`ConsentRecord` is THIS PROJECT'S OWN consent basis for lane
  ``C``/``C_pending_consent`` capture. ``consent_posture`` instead
  describes a THIRD PARTY dataset's own subjects, for lane R specifically
  — nothing this project did or can retroactively fix, only something it
  must not misrepresent by omission.

Like ``hypothesis_class``, a value here is a recorded hypothesis from
public documentation and project memory, not an independently re-verified
fact — ``unknown`` is the honest default whenever that hypothesis is not
solid, including for non-people-centric datasets (scene/depth scans) where
the staged/uncontrolled distinction does not obviously apply. ``None``
(the field's default) is reserved for lanes where the concept is genuinely
inapplicable in a different way — lane S (no real subjects at all, or the
subject question is answered by ``asset_clearance`` instead) and lane
C/C_pending_consent (governed by ``consent_record``, not this field)."""

Hosting = Literal["huggingface", "direct_url", "other", "unknown"]
"""HOW a dataset's canonical page is hosted — a fourth axis, orthogonal to
the other three the registry already tracks:

- ``hypothesis_class`` / :class:`LicenseSnapshot` — COPYRIGHT.
- :data:`ConsentPosture` / :class:`ConsentRecord` — SUBJECT CONSENT.
- :class:`DeploymentScopeRestriction` — DEPLOYMENT-USE SCOPE.
- ``hosting`` — none of those. It answers a purely mechanical question a
  license read cannot: is the URL a dataset's terms live at a STATIC file
  (a GitHub ``LICENSE``, safe to ``urlopen`` and hash directly), or a
  SERVER-RENDERED page that can embed per-request-volatile state around
  otherwise-stable text (Day 39, found on CHIRLA's HuggingFace dataset
  card — two fetches of the same unchanged license text minutes apart
  hashed differently because the page also carries live download/like
  counts and a ``lastModified`` timestamp)? Getting this wrong does not
  misjudge a license; it makes ``LicenseSnapshot.text_sha256`` noise, which
  is worse than an honest failure because it look like recorded evidence.

Read by :func:`scripts.fetch_dataset.verify_license` to choose a
verification strategy BEFORE any URL is touched — the routing is this
typed field, never a domain string sniffed out of ``--license-url`` deep
inside the function body, so a HuggingFace-hosted entry cannot silently
fall through to the naive whole-response hash by an unclassified URL
shape.

``"unknown"`` is the honest default, the same convention
:data:`ConsentPosture` uses — most of this registry's 63 entries have
never had their actual hosting mechanism confirmed (see
``docs/registry_deployment_scope_audit.md``, the same audit that will
eventually do this classification too). ``"direct_url"`` is a static file
already safe for the existing ``urlopen``-and-hash path (MEVA's tarball
license is the model case). ``"other"`` is reserved for a hosting
mechanism that is neither — recorded so a human classifying an entry is
never forced to mis-pick between the two real categories just because a
third option did not exist."""

